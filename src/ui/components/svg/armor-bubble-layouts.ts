import type { BattleMech } from "../../../classes/battlemech";

/*
 * Where each armor bubble sits on the 'Mech record sheet's armor diagram. A location shows one bubble per point of
 * armor allocated to it, filled in this order. Each point is the bubble's center as [x, y]: x from the armor box's
 * center line, y from its top. One shared renderer draws them all (renderArmorBubbles), instead of one hand-written
 * line per bubble (#589).
 */

export type ArmorAllocationField = keyof ReturnType<BattleMech["getArmorAllocation"]>;

export interface IArmorBubbleLocation {
    /** The armor allocation that says how many of this location's bubbles to draw. */
    field: ArmorAllocationField;
    /** The location code that armor damage and bubble clicks use. */
    loc: string;
    radius: number;
    points: BubblePoint[];
}

export type BubblePoint = [number, number];

/** The closest two bubbles' spacing along x or y, or a bubble's width when there is only one. */
const closestSpacing = (points: BubblePoint[], radius: number): number => {
    let spacing = 2 * radius;
    for (let i = 0; i < points.length; i++) {
        for (let j = i + 1; j < points.length; j++) {
            spacing = Math.min(spacing, Math.max(Math.abs(points[i][0] - points[j][0]), Math.abs(points[i][1] - points[j][1])));
        }
    }
    return spacing;
};

/**
 * Where a location's first `count` bubbles go, filling from the center of its area outward. Past its table (a
 * superheavy, or an armor that may one day double today's allowance) each table bubble splits into a square cluster of
 * smaller ones inside its own footprint, so the location still shows a bubble per point.
 */
export const bubblePositions = (points: BubblePoint[], radius: number, count: number): { points: BubblePoint[]; radius: number } => {
    const wanted = Math.max(Math.floor(count), 0);
    if (points.length === 0 || wanted === 0) {
        return { points: [], radius };
    }
    const split = Math.max(Math.ceil(Math.sqrt(wanted / points.length)), 1);
    const cell = closestSpacing(points, radius) / split;
    const offsets = Array.from({ length: split }, (_, i) => (i - (split - 1) / 2) * cell);
    const placed: BubblePoint[] = split === 1 ? points : points.flatMap(([x, y]) =>
        offsets.flatMap((dy) => offsets.map((dx): BubblePoint => [x + dx, y + dy])));
    const centerX = points.reduce((sum, [x]) => sum + x, 0) / points.length;
    const centerY = points.reduce((sum, [, y]) => sum + y, 0) / points.length;
    const fromCenter = ([x, y]: BubblePoint) => Math.hypot(x - centerX, y - centerY);
    const ordered = [...placed].sort((a, b) => fromCenter(a) - fromCenter(b) || a[1] - b[1] || a[0] - b[0]);
    return { points: ordered.slice(0, wanted), radius: split === 1 ? radius : cell * 0.45 };
};

/** The smallest bubble footprint drawn as-is: DamageCircleSVG's circle, 3 short of it, is still a ring at 5 wide. */
const FULL_SIZE_FOOTPRINT = 8;

/**
 * The DamageCircleSVG radius and stroke for a bubble of this footprint. DamageCircleSVG draws 3 short of its radius
 * with a 2-wide stroke, so a smaller bubble (a split superheavy location, a Tripod's Center Leg) would draw as a black
 * dot, damaged or not; it is drawn as a scaled-down full-size bubble instead.
 */
export const drawnBubble = (footprint: number): { radius: number; strokeWidth: number } => {
    if (footprint >= FULL_SIZE_FOOTPRINT) {
        return { radius: footprint, strokeWidth: 2 };
    }
    const scale = footprint / FULL_SIZE_FOOTPRINT;
    return { radius: (FULL_SIZE_FOOTPRINT - 3) * scale + 3, strokeWidth: 2 * scale };
};

