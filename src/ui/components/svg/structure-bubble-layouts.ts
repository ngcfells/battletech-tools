/*
 * Where each internal structure bubble sits on the 'Mech record sheet's structure diagram, one bubble per point of
 * structure, as [x, y] from the structure box's center line and top. renderStructureBubbles fills each location from
 * its center outward and, past the table (a superheavy), splits bubbles into smaller ones in the same footprint (#589).
 */

export interface IStructureBubbleLocation {
    /** The internal structure value that says how many of this location's bubbles to draw. */
    field: keyof IResolvedInternalStructure;
    /** The location code that structure damage and bubble clicks use. */
    loc: string;
    radius: number;
    points: BubblePoint[];
}

